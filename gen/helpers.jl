# Generic trait checks
is_imgui_struct(x) = x.stname !== ""
isdestructor(x) = hasproperty(x, :destructor)
isconstructor(x) = hasproperty(x, :constructor)
is_static_function(x) = get(x, "is_static_function", false) === true

#ImPlot specific
isplotfunction(x) = startswith(x.funcname, "Plot") && !startswith(x.funcname, "PlotToPixels")

hasdefault(metadata, sym) = hasproperty(metadata.defaults, sym)
getdefault(metadata, sym) = getproperty(metadata.defaults, sym)
get_jl_type(argtype) = argtype ∈ IMDATATYPES ? IMTOJL_LOOKUP[argtype] : argtype

function read_metadata()
    json_enums = read(CImGuiPack_jll.cimplot_structs_and_enums, String);
    json_defs = read(CImGuiPack_jll.cimplot_definitions, String);
    #json_typedefs = read(joinpath(METADATA_DIR, "typedefs_dict.json"), String);
    STRUCTS_AND_ENUMS = JSON.parse(json_enums);
    #types = JSON.parse(json_typedefs);
    FUNCTION_METADATA = JSON.parse(json_defs);
    ENUMS = Symbol.(chop.(keys(STRUCTS_AND_ENUMS.enums)))
    # enum constant name (e.g. "ImPlotBin_Sturges") -> enum type symbol (e.g. :ImPlotBin_)
    ENUM_CONSTANTS = Dict(c.name => Symbol(etype)
                          for etype in keys(STRUCTS_AND_ENUMS.enums)
                          for c in STRUCTS_AND_ENUMS.enums[etype])
    return FUNCTION_METADATA, STRUCTS_AND_ENUMS, ENUMS, ENUM_CONSTANTS
end

# Check if originally from implot_internal.h; this filters most internal functions
function internal_check(x)
    if hasproperty(x, :location)
        startswith(x.location, "implot_internal") && return true
    end
    return false
end

"""
Destructure the `@ccall libcimgui.funsymbol(argname::argtype...)::rettype`
expression generated by Clang.jl.
"""
function split_ccall(body)
    for ex in body.args
        if Meta.isexpr(ex, :macrocall) && ex.args[1] == Symbol("@ccall")
            call, rettype = ex.args[3].args
            funsymbol = call.args[1].args[2].value
            argnames = [arg.args[1] for arg in call.args[2:end]]
            argtypes = [arg.args[2] for arg in call.args[2:end]]
            return (funsymbol, rettype, argtypes, argnames)
        end
    end

    error("Could not find a @ccall expression in: $(body)")
end

"""
Create a `@ccall` expression. The line number is set to `nothing` like Clang.jl
does so that it doesn't get printed in the generated code.
"""
function make_ccall(funsymbol, rettype, argtypes, argnames)
    args = [:($name::$type) for (name, type) in zip(argnames, argtypes)]
    return Expr(:macrocall, Symbol("@ccall"), nothing, :(libcimgui.$funsymbol($(args...))::$rettype))
end

is_null_default(str) = str in ("((void*)0)", "NULL", "nullptr")

function parse_default(jlsymtype, str, ptr_type = nothing)
    T = eval(jlsymtype)
    is_null_default(str) && return :C_NULL
    (T <: AbstractFloat || T <: Bool || T <: Cstring) && return Meta.parse(str)
    T <: Integer && return (startswith(str, "sizeof") ? :(sizeof($ptr_type)) : Meta.parse(str))
    T <: Symbol && return Symbol(str)
    return @warn "Not parsing default value of: $str"
end

"""
Annotate a `void*` user data argument. These are annotated so that they don't
create ambiguities with overloads that have a scalar argument in the same
position (e.g. the PlotPieChart formatter/format string variants).

Note that we deliberately don't add the C `nullptr` defaults, because that would
change which overload some calls dispatch to.
"""
function annotate_void_ptr!(def, i, sym)
    def[:args][i] = :($sym::Union{Ptr,Ref,AbstractArray})
end

function revise_arg(def, metadata, i, sym, jltype, ptr_type = nothing)
    if jltype ∈ (:Cint, :Clong, :Cshort, :Cushort, :Culong, :Cuchar, :Cchar,
                 :Int8, :UInt8, :Int16, :UInt16, :Int32, :UInt32, :Int64, :UInt64)
        if hasdefault(metadata, sym)
            raw = getdefault(metadata, sym)
            val = parse_default(jltype, raw, ptr_type)
            # an enum-constant default (e.g. ImPlotBin_Sturges) means this C `int` param also
            # accepts that enum (like flag params) -> widen the annotation to admit both.
            enumT = get(ENUM_CONSTANTS, String(raw), nothing)
            argann = isnothing(enumT) ? :($sym::Integer) : :($sym::Union{$enumT,Integer})
            def[:args][i] = :($(Expr(:kw, argann, val)))
        else
            def[:args][i] = :($sym::Integer)
        end
        return
    elseif jltype ∈ (:Cfloat, :Cdouble, :Float64, :Float32)
        if hasdefault(metadata, sym)
            val = parse_default(jltype, getdefault(metadata,sym), ptr_type)
            def[:args][i] = :($( Expr(:kw, :($sym::Real), val)) )
        else
            def[:args][i] = :($sym::Real)
        end
        return
    elseif jltype ∈ (:Cstring,:Bool)
        # Don't annotate strings--we want option to pass C_NULL
        # Don't annotate Bool, we want option to pass 0 or 1
        if hasdefault(metadata, sym)
            val = parse_default(jltype, getdefault(metadata, sym), ptr_type)
            def[:args][i] = :($(Expr(:kw, sym, val)))
        end
        return
    elseif startswith(string(jltype), "Im") # Heuristic for imgui types
        if hasdefault(metadata, sym)
            raw_val = getdefault(metadata,sym)
            if  raw_val == "((void*)0)"
                val = :C_NULL
                def[:args][i] = :($(Expr(:kw, sym, val)) )
                return
            elseif startswith(raw_val, "Im")
                if jltype in IMGUI_ISBITS_TYPES
                    def[:args][i] = :($(Expr(:kw, :($sym::$jltype), Meta.parse(raw_val))))
                else
                    def[:args][i] = :($(Expr(:kw, sym, Meta.parse(raw_val))))
                end
                return
            elseif jltype in ENUMS
                def[:args][i] = :($(Expr(:kw, :($sym::Union{$(Symbol(string(jltype)*"_")),Integer}), Meta.parse(raw_val))))
                return
            else
                def[:args][i] = :($(Expr(:kw, sym, Meta.parse(raw_val))))
                return
            end
        elseif jltype in ENUMS
            def[:args][i] = :($sym::Union{$(Symbol(string(jltype)*"_")),Integer})
            return
        else
            def[:args][i] = :($sym::$jltype)
            return
        end
    elseif @capture(jltype, Ptr{ptrtype_}) # if pointer argument + capture eltype
        if ptrtype == :Cvoid
            annotate_void_ptr!(def, i, sym)
        elseif hasdefault(metadata, sym)
            raw_val = getdefault(metadata,sym)
            if raw_val !== "((void*)0)" && endswith(raw_val, r"\(.+\)")
                rx = match(r"\(.+\)",raw_val)
                tupex = Meta.parse(rx.match)
                def[:args][i] = :($(Expr(:kw,
                                         :($sym::Union{$ptrtype,AbstractArray{$ptrtype}}), :($ptrtype($(tupex.args...))))))
            end
        elseif ptrtype == :Cstring
            def[:args][i] = :($sym::Union{Ptr{Nothing},String,AbstractArray{String}})
        else
            def[:args][i] = :($sym::Union{$ptrtype,AbstractArray{$ptrtype}})
        end
        return
    end
    @info "Not processing argument: $sym::$jltype from $(def[:name])"
    return
end

function generate_plotmethod(def, metadata)
    def[:name] = Symbol(metadata.funcname)
    (funsymbol, rettype, argtypes, argnames) = split_ccall(def[:body])
    datatype = :notparsed
    for (i, argtype) in enumerate(argtypes)
        sym = argnames[i]
        jltype = get_jl_type(argtype)
        if @capture(jltype, Ptr{ptrtype_}) && ptrtype ∈ IMDATATYPES
            datatype = ptrtype
            def[:args][i] = :($sym::Union{Ptr{$ptrtype},Ref{$ptrtype},AbstractArray{$ptrtype}})
        else
            revise_arg(def, metadata, i, sym, jltype, datatype)
        end
    end
    def[:body] = Expr(:block, make_ccall(funsymbol, rettype, argtypes, argnames))
    return ExprTools.combinedef(def)
end

function make_finalizer!(def, metadata)
    def[:name] = :(Base.finalizer)
    (funsymbol, rettype, argtypes, argnames) = split_ccall(def[:body])
    argtype, argname = only(argtypes), only(argnames)
    @capture(argtype, Ptr{ptrtype_})
    def[:args] = [:($argname::Union{$argtype,$ptrtype})]
    new_ccall = make_ccall(funsymbol, rettype, [argtype], [argname])
    new_body = Expr(:block, :(ptr = pointer_from_objref($argname)), :(GC.@preserve $argname $new_ccall))
    def[:body] = MacroTools.prewalk(rmlines, new_body)
end

function make_constructor!(def, metadata)
    def[:name] = Symbol(metadata.stname)
    (funsymbol, rettype, argtypes, argnames) = split_ccall(def[:body])
    def[:body] = Expr(:block, make_ccall(funsymbol, rettype, argtypes, argnames))
end

function parse_pointer_arg!(jltype, def, metadata, sym, i)
    if @capture(jltype, Ptr{ptrtype_})
        if ptrtype in (IMDATATYPES..., :Cstring, :Bool)
            if ptrtype == :Cstring
                arg_type = :($sym::Union{Ptr{Nothing},String,AbstractArray{String}})
                null_default = :C_NULL                       # member of the Ptr{Nothing} union
            elseif ptrtype == :Bool
                arg_type = def[:args][i] = :($sym)
                null_default = :C_NULL                       # unannotated
            else
                arg_type = :($sym::Union{Ptr{$ptrtype},Ref{$ptrtype},AbstractArray{$ptrtype}})
                null_default = :(Ptr{$ptrtype}())            # typed null: Ptr{T} <: Ref{T} ∈ the union
            end

            if hasdefault(metadata, sym)
                raw = getdefault(metadata, sym)
                val = is_null_default(raw) ? null_default : parse_default(jltype, raw, ptrtype)
                def[:args][i] = :($(Expr(:kw, arg_type, val)))
            else
                def[:args][i] = arg_type
            end

            return true
        elseif ptrtype == :Cvoid
            annotate_void_ptr!(def, i, sym)
            return true
        elseif ptrtype ∉ vcat(IMGUI_ISBITS_TYPES, IMDATATYPES)
            return true
        end
    end
    return false
end

function make_objmethod!(def, metadata)
    def[:name] = Symbol(metadata.funcname)
    (funsymbol, rettype, argtypes, argnames) = split_ccall(def[:body])

    # Handle the 'self' argument
    firstsym, firstargtype = first(argnames), first(argtypes)
    @capture(firstargtype, Ptr{ptr_type_})
    def[:args][1] = :($firstsym::Union{$ptr_type,$firstargtype,Ref{$ptr_type}})

    # parse remaining arguments
    for (i, argtype) in enumerate(argtypes)
        i == 1 && continue
        sym = argnames[i]
        jltype = get_jl_type(argtype)
        # Skip pointer types
        parse_pointer_arg!(jltype, def, metadata, sym, i) && continue
        revise_arg(def, metadata, i, sym, jltype)
    end
end

function generate_generic(def, metadata)
    def[:name] = Symbol(metadata.funcname)
    (funsymbol, rettype, argtypes, argnames) = split_ccall(def[:body])
    def[:body] = Expr(:block, make_ccall(funsymbol, rettype, argtypes, argnames))

    for (i, argtype) in enumerate(argtypes)
        sym = argnames[i]
        jltype = get_jl_type(argtype)

        # Remove type annotations from functions labeled DESPECIALIZE
        if metadata.funcname in DESPECIALIZE
            def[:args][i] = :($sym)
            continue
        end

        parse_pointer_arg!(jltype, def, metadata, sym, i) && continue
        revise_arg(def, metadata, i, sym, jltype)
    end
    return ExprTools.combinedef(def)
end

function get_function_name(def)
    # Skip Expr function names (e.g. :(Base.getproperty))
    # FIXME: sometimes getting functors??!!
    def[:name] isa Symbol || return nothing
    return string(def[:name])
end

function find_function_metadata(fun_name, metadata)
    for object_vector in values(metadata), fun_meta in object_vector
        if fun_name == fun_meta.ov_cimguiname || fun_name == fun_meta.cimguiname
            return fun_meta
        end
    end
    return nothing
end

function generate_struct_function(def, metadata, old_ex)
    # Skip constructors/destructors for primitive types--we can handle these with Julia
    if metadata.stname ∉ String.(IMGUI_ISBITS_TYPES)
        if hasproperty(metadata, :destructor)
            make_finalizer!(def, metadata)
            return ExprTools.combinedef(def)
        elseif hasproperty(metadata, :constructor)
            # write contructor...
            make_constructor!(def, metadata)
            return ExprTools.combinedef(def)
        end
    end
    # Fall through to object method; skip destructors
    if !(isdestructor(metadata) || isconstructor(metadata))
        make_objmethod!(def,metadata)
        # Reconstitute function definition expression
        return ExprTools.combinedef(def)
    else
        return old_ex
    end
end

function create_docstring(metadata)
    docstring = ""

    comment = get(metadata, "comment", "")
    if !isempty(comment)
        comment = replace(comment, "\\0" => "\\\\0")
        formatted_comment = chopprefix(comment, "//") |> strip |> uppercasefirst
        if !isempty(formatted_comment) && formatted_comment[end] ∉ ('.', '!', '?')
            formatted_comment *= "."
        end

        docstring *= "\n\n$(formatted_comment)"
    end

    header, line = split(metadata["location"], ':')
    implot_version = "851cdbd"
    link = "https://github.com/epezent/implot/blob/$(implot_version)/$(header).h#L$(line)"

    if internal_check(metadata)
        docstring *= """\n
                     !!! warning
                         This function is internal, it may change in the future.\n
                     """
    end

    docstring *= "[Upstream link]($link)."

    return docstring
end

"""
Check if a C function name is in the output ignorelist. This mirrors Clang.jl's
`should_exclude_node()`, which requires the regexes to match the whole name.
"""
function is_ignored(c_name, options)
    for pattern in options["general"]["output_ignorelist"]
        m = match(Regex(pattern), c_name)
        if !isnothing(m) && m.match == c_name
            return true
        end
    end

    return false
end

function revise_function(ex::Expr, all_metadata, options, docstrings, public_names)
    # Destructure the function definition
    def = ExprTools.splitdef(ex)

    # Get & validate function name
    fun_name = get_function_name(def)
    isnothing(fun_name) && return ex

    metadata = find_function_metadata(fun_name, all_metadata)

    # Skip functions not in the JSON metadata
    if isnothing(metadata)
        @warn "Could not find function: $fun_name in JSON metadata"
        return ex
    end

    # Check if it's for a struct type
    try
        ex = if is_imgui_struct(metadata) && !is_static_function(metadata)
            generate_struct_function(def, metadata, ex)
        elseif isplotfunction(metadata) # implot specific
            generate_plotmethod(def, metadata)
        else
            generate_generic(def, metadata)
        end
    catch
        @error "Failed to wrap $(fun_name)"
        rethrow()
    end

    # Generate docstrings for everything but destructors
    if !endswith(fun_name, "_destroy")
        docstrings[fun_name] = create_docstring(metadata)
    end

    # A Julia function is public if it has any non-internal methods. Names like
    # `:(Base.finalizer)` belong to other modules so we skip them, and functions
    # in the ignorelist won't be printed so we skip them too.
    if def[:name] isa Symbol && !internal_check(metadata) && !is_ignored(fun_name, options)
        push!(public_names, def[:name])
    end

    return ex
end

"""
Get the names of all types, enums, and enum constants from `implot_internal.h`.
"""
function internal_type_symbols()
    enums = STRUCTS_AND_ENUMS["enums"]

    syms = Set{Symbol}()
    for (name, location) in STRUCTS_AND_ENUMS["locations"]
        if !startswith(location, "implot_internal")
            continue
        end

        push!(syms, Symbol(name))
        if haskey(enums, name)
            # The enum typedef, e.g. `ImPlotTimeUnit` for `ImPlotTimeUnit_`
            push!(syms, Symbol(chopsuffix(name, "_")))
            for c in enums[name]
                push!(syms, Symbol(c.name))
            end
        end
    end

    return syms
end

"""
Generate the `export` and `public` statements for the bindings. Everything
prefixed with one of `prefixes` is exported, except for the types from
`implot_internal.h`. All other `public_names` are marked as public.
"""
function generate_exports(public_names, prefixes)
    internal_syms = internal_type_symbols()
    is_exported(name) = any(p -> startswith(string(name), p), prefixes)
    public_names = filter(x -> !is_exported(x) && !startswith(string(x), "_"), public_names)

    internal_list = join(":" .* sort(string.(collect(internal_syms))), ", ")
    public_list = join(sort(string.(collect(public_names))), ", ")

    return """
    # exports
    let prefixes = $(repr(prefixes)), internal = Set([$(internal_list)])
        for name in names(@__MODULE__; all=true)
            if any(p -> startswith(string(name), p), prefixes) && name ∉ internal
                @eval export \$name
            end
        end
    end

    @static if VERSION >= v"1.11"
        eval(Meta.parse("public $(public_list)"))
    end
    """
end

"""
Get the names of all the top-level functions defined in a file.
"""
function function_names(path)
    names = Symbol[]
    for ex in Meta.parseall(read(path, String)).args
        if Meta.isexpr(ex, :function) && Meta.isexpr(ex.args[1], :call)
            push!(names, ex.args[1].args[1])
        end
    end

    return names
end

function rewrite!(dag::ExprDAG, metadata, options, docstrings, public_names)
    # In newer versions of the cimgui bindings non-POD-types-that-look-like-POD-types-but-actually-aren't
    # are renamed to have a '_c' underscore. In the generated Julia bindings we
    # rename these back to their old names for the sake of convenience.
    # See: https://github.com/cimgui/cimgui/issues/309
    nonpod_used = STRUCTS_AND_ENUMS["nonPOD_used"]
    new2old_names = Dict([Symbol(x, "_c") => Symbol(x) for x in keys(nonpod_used)])

    for node in get_nodes(dag)
        expressions = get_exprs(node)
        for (i, expr) in enumerate(expressions)
            if Meta.isexpr(expr, :function)
                expressions[i] = revise_function(expr, metadata, options, docstrings, public_names)
            end

            expressions[i] = postwalk(expressions[i]) do x
                if x isa Symbol && x in keys(new2old_names)
                    new2old_names[x]
                else
                    x
                end
            end
        end
    end
end

# Generation of the high-level plotting methods that accept Julia arrays. All
# the plot functions that can be wrapped follow the same pattern:
#
#     ImPlot_PlotX_<types>(const char* label_id, const T* a, const T* b, ..., int count,
#                          <scalar args>..., const ImPlotSpec_c spec)
#
# For each of these we generate:
# - An array method that takes all the data pointers as `AbstractArray{<:Real}`,
#   checks their lengths, coerces them to a common type, and passes `count`
#   automatically. The scalar arguments become keyword arguments.
# - If the scalar arguments include an `xscale`/`xstart` pair (or `scale`/`start`),
#   a method that takes the x values as an `AbstractRange`.
# - If the data pointers are exactly `xs` and `ys`, a method that extracts the
#   x and y values from fields of a vector of structs.

const NUMERIC_PTR_REGEX = r"^const (float|double|ImS8|ImU8|ImS16|ImU16|ImS32|ImU32|ImS64|ImU64)\*$"
const SCALE_START_PAIRS = [("xscale", "xstart"), ("scale", "start")]

struct PlotFamily
    funcname::String
    metadata::Any # The metadata of one of the type variants
    arrays::Vector{String} # Names of the data pointer arguments
    scalars::Vector{Any} # argsT entries for the arguments between count and spec
end

"""
Find all the plot function overloads that follow the standard pattern,
deduplicating the type variants.
"""
function find_plot_families(all_metadata)
    families = Dict{Tuple{String, Vector{String}}, PlotFamily}()

    for (cname, overloads) in all_metadata
        if !startswith(cname, "ImPlot_Plot")
            continue
        end

        for m in overloads
            if internal_check(m)
                continue
            end

            names = [a.name for a in m.argsT]
            types = [a.type for a in m.argsT]
            count_idx = findfirst(==("count"), names)
            if isnothing(count_idx) || names[1] != "label_id" || names[end] != "spec"
                continue
            end

            # All the arguments between label_id and count must be numeric data pointers
            if count_idx < 3 || !all(t -> occursin(NUMERIC_PTR_REGEX, t), types[2:count_idx - 1])
                continue
            end

            # The type variants have the same argument names
            key = (m.funcname, names)
            if !haskey(families, key)
                families[key] = PlotFamily(m.funcname, m, names[2:count_idx - 1],
                                           collect(m.argsT[count_idx + 1:end - 1]))
            end
        end
    end

    return sort(collect(values(families)); by=f -> (f.funcname, length(f.arrays), f.arrays))
end

"""
Get the default value of an argument, looking at other overloads of the same
function if this one doesn't have a default (e.g. `bar_size` for `PlotBars`).
"""
function plot_arg_default(family, argname, all_metadata)
    cname = "ImPlot_" * family.funcname
    for m in Iterators.flatten(((family.metadata,), all_metadata[cname]))
        if haskey(m.defaults, argname)
            return m.defaults[argname]
        end
    end

    return nothing
end

"""
Convert a scalar C argument to a keyword argument expression.
"""
function plot_kwarg(family, arg, all_metadata)
    sym = Symbol(arg.name)
    ctype = chopsuffix(arg.type, "_c")
    default = plot_arg_default(family, arg.name, all_metadata)

    annotation = if ctype in ("double", "float")
        :Real
    elseif ctype in ("int", "ImS32", "ImU32", "ImS64", "ImU64")
        enumT = isnothing(default) ? nothing : get(ENUM_CONSTANTS, default, nothing)
        isnothing(enumT) ? :Integer : :(Union{$enumT, Integer})
    elseif startswith(ctype, "ImPlot")
        Symbol(ctype)
    else
        error("Unsupported argument type for $(family.funcname): $(arg.type) $(arg.name)")
    end

    typed_sym = :($sym::$annotation)
    return isnothing(default) ? typed_sym : Expr(:kw, typed_sym, Meta.parse(default))
end

function length_check(funcname, arrays)
    # Nothing to check with a single array. Note that we return an empty block
    # rather than `nothing` because `nothing` would get interpolated into the
    # function body, whereas the empty block gets removed by `prettify()`.
    if length(arrays) == 1
        return Expr(:block)
    end

    lengths = :(($([:(length($(Symbol(a)))) for a in arrays]...),))
    message = Expr(:string, "$(funcname): $(join(arrays, "/")) lengths differ ", lengths)

    return quote
        if !allequal($lengths)
            throw(DimensionMismatch($message))
        end
    end
end

function coerce_arrays(arrays)
    syms = Symbol.(arrays)
    if length(syms) == 1
        return :($(syms[1]) = _coerce($(syms[1])))
    else
        return :(($(syms...),) = _coerce($(syms...)))
    end
end

function plot_docstring(family)
    return "\$(TYPEDSIGNATURES)\n\n" * lstrip(create_docstring(family.metadata))
end

"""
Generate the methods for a single plot family. Returns a vector of (docstring,
expression) tuples.
"""
function generate_plot_family(family, all_metadata)
    fname = Symbol(family.funcname)
    arrays = Symbol.(family.arrays)
    array_args = [:($a::AbstractArray{<:Real}) for a in arrays]
    scalar_syms = [Symbol(a.name) for a in family.scalars]
    kwargs = [plot_kwarg(family, a, all_metadata) for a in family.scalars]
    spec_kwarg = Expr(:kw, :(spec::ImPlotSpec), :(ImPlotSpec()))
    docstring = plot_docstring(family)
    methods = []

    # Array method
    push!(methods, (docstring, :(
        function $fname(label_id, $(array_args...); $(kwargs...), $spec_kwarg)
            $(length_check(family.funcname, family.arrays))
            $(coerce_arrays(family.arrays))
            return $fname(label_id, $(arrays...), length($(arrays[1])), $(scalar_syms...), spec)
        end
    )))

    # Range method
    scalar_names = [a.name for a in family.scalars]
    pair_idx = findfirst(p -> p[1] in scalar_names && p[2] in scalar_names, SCALE_START_PAIRS)
    if !isnothing(pair_idx)
        scale_name, start_name = SCALE_START_PAIRS[pair_idx]
        range_kwargs = [kw for (kw, name) in zip(kwargs, scalar_names) if name ∉ (scale_name, start_name)]
        call_args = map(scalar_names) do name
            if name == scale_name
                :(step(x))
            elseif name == start_name
                :(first(x))
            else
                Symbol(name)
            end
        end

        push!(methods, (docstring, :(
            function $fname(label_id, x::AbstractRange, $(array_args...); $(range_kwargs...), $spec_kwarg)
                $(length_check(family.funcname, ["x"; family.arrays]))
                $(coerce_arrays(family.arrays))
                return $fname(label_id, $(arrays...), length($(arrays[1])), $(call_args...), spec)
            end
        )))
    end

    # Struct field method
    if family.arrays == ["xs", "ys"]
        push!(methods, (docstring, :(
            function $fname(label_id, data::AbstractVector, xfield::Symbol, yfield::Symbol; $(kwargs...), $spec_kwarg)
                return _plot_structfields($fname, label_id, data, xfield, yfield, spec, $(scalar_syms...))
            end
        )))
    end

    return methods
end

"""
Write the high-level plotting methods to `output_file`.
"""
function generate_plot_wrappers(all_metadata, output_file)
    families = find_plot_families(all_metadata)

    open(output_file, "w") do io
        write(io, """
              # This file is automatically generated by gen/generator.jl, DO NOT EDIT.
              # It contains high-level methods for the plotting functions that accept
              # Julia arrays.

              """)

        for family in families, (docstring, ex) in generate_plot_family(family, all_metadata)
            write(io, "\"\"\"\n$(docstring)\n\"\"\"\n")
            write(io, string(MacroTools.prettify(ex)), "\n\n")
        end
    end

    format_file(output_file; margin=120)
end
